 public.financial_accounts,public.sales_invoices,public.sales_invoice_lines,public.purchase_invoices,public.purchase_invoice_lines,
 public.expenses,public.other_income,public.stock_movements,public.money_movements,public.journal_entries,public.journal_lines to authenticated;
