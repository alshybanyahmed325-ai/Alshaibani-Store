-- Shaybani accounting starter schema
-- Run only in a NEW dedicated Supabase project after review.
create extension if not exists pgcrypto;

create table if not exists public.app_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'operator' check (role in ('owner','admin','accountant','operator','viewer')),
  created_at timestamptz not null default now()
);

create table if not exists public.currencies (
  code text primary key check (code in ('YER','SAR','USD')),
  name_ar text not null,
  is_base boolean not null default false,
  active boolean not null default true
);
insert into public.currencies(code,name_ar,is_base) values
 ('YER','ريال يمني',true),('SAR','ريال سعودي',false),('USD','دولار أمريكي',false)
on conflict(code) do nothing;

create table if not exists public.exchange_rates (
 id uuid primary key default gen_random_uuid(),
 base_currency text not null references public.currencies(code),
 quote_currency text not null references public.currencies(code),
 rate numeric(20,8) not null check(rate>0),
 effective_at timestamptz not null default now(),
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now(),
 unique(base_currency,quote_currency,effective_at)
);

create table if not exists public.units (
 id uuid primary key default gen_random_uuid(),
 name_ar text not null unique,
 abbreviation text,
 created_at timestamptz not null default now()
);
insert into public.units(name_ar,abbreviation) values
 ('كيلو','kg'),('جرام','g'),('نصف كيلو','0.5kg'),('ربع كيلو','0.25kg'),('عبوة','pack'),('حبة','piece'),('لتر','L')
on conflict(name_ar) do nothing;

create table if not exists public.products (
 id uuid primary key default gen_random_uuid(),
 sku text unique,
 name text not null,
 category text,
 base_unit_id uuid references public.units(id),
 quantity numeric(18,3) not null default 0 check(quantity>=0),
 purchase_price numeric(20,4) not null default 0 check(purchase_price>=0),
 sale_price numeric(20,4) not null default 0 check(sale_price>=0),
 currency text not null default 'YER' references public.currencies(code),
 minimum_stock numeric(18,3) not null default 0 check(minimum_stock>=0),
 notes text,
 version integer not null default 1,
 device_id text,
 deleted_at timestamptz,
 created_by uuid references auth.users(id),
 updated_by uuid references auth.users(id),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index if not exists products_name_idx on public.products using gin (to_tsvector('simple',coalesce(name,'')));
create index if not exists products_updated_idx on public.products(updated_at desc);

create table if not exists public.customers (
 id uuid primary key default gen_random_uuid(), name text not null, phone text, address text,
 opening_balance numeric(20,4) not null default 0, currency text not null default 'YER' references public.currencies(code),
 notes text, deleted_at timestamptz, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.suppliers (
 id uuid primary key default gen_random_uuid(), name text not null, phone text, address text,
 opening_balance numeric(20,4) not null default 0, currency text not null default 'YER' references public.currencies(code),
 notes text, deleted_at timestamptz, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.financial_accounts (
 id uuid primary key default gen_random_uuid(), name text not null, account_type text not null check(account_type in ('cashbox','bank','wallet','other')),
 currency text not null references public.currencies(code), opening_balance numeric(20,4) not null default 0,
 active boolean not null default true, created_at timestamptz not null default now()
);

create table if not exists public.sales_invoices (
 id uuid primary key default gen_random_uuid(), invoice_no bigint generated by default as identity unique,
 customer_id uuid references public.customers(id), status text not null default 'draft' check(status in ('draft','posted','void')),
 currency text not null references public.currencies(code), exchange_rate numeric(20,8) not null default 1 check(exchange_rate>0),
 subtotal numeric(20,4) not null default 0, discount numeric(20,4) not null default 0, total numeric(20,4) not null default 0,
 paid numeric(20,4) not null default 0, notes text, created_by uuid references auth.users(id),
 created_at timestamptz not null default now(), posted_at timestamptz
);
create table if not exists public.sales_invoice_lines (
 id uuid primary key default gen_random_uuid(), invoice_id uuid not null references public.sales_invoices(id) on delete restrict,
 product_id uuid not null references public.products(id) on delete restrict, unit_name text not null,
 quantity numeric(18,3) not null check(quantity>0), unit_price numeric(20,4) not null check(unit_price>=0),
 discount numeric(20,4) not null default 0, line_total numeric(20,4) not null check(line_total>=0),
 base_quantity numeric(18,3) not null check(base_quantity>0), created_at timestamptz not null default now()
);
create table if not exists public.purchase_invoices (
 id uuid primary key default gen_random_uuid(), invoice_no bigint generated by default as identity unique,
 supplier_id uuid references public.suppliers(id), status text not null default 'draft' check(status in ('draft','posted','void')),
 currency text not null references public.currencies(code), exchange_rate numeric(20,8) not null default 1 check(exchange_rate>0),
 subtotal numeric(20,4) not null default 0, discount numeric(20,4) not null default 0, total numeric(20,4) not null default 0,
 paid numeric(20,4) not null default 0, notes text, created_by uuid references auth.users(id),
 created_at timestamptz not null default now(), posted_at timestamptz
);
create table if not exists public.purchase_invoice_lines (
 id uuid primary key default gen_random_uuid(), invoice_id uuid not null references public.purchase_invoices(id) on delete restrict,
 product_id uuid not null references public.products(id) on delete restrict, unit_name text not null,
 quantity numeric(18,3) not null check(quantity>0), unit_cost numeric(20,4) not null check(unit_cost>=0),
 discount numeric(20,4) not null default 0, line_total numeric(20,4) not null check(line_total>=0),
 base_quantity numeric(18,3) not null check(base_quantity>0), created_at timestamptz not null default now()
);
create table if not exists public.expenses (
 id uuid primary key default gen_random_uuid(), expense_date date not null default current_date,
 category text not null, description text not null, amount numeric(20,4) not null check(amount>0),
 currency text not null references public.currencies(code), account_id uuid references public.financial_accounts(id),
 created_by uuid references auth.users(id), created_at timestamptz not null default now()
);
create table if not exists public.other_income (
 id uuid primary key default gen_random_uuid(), income_date date not null default current_date,
 category text not null, description text not null, amount numeric(20,4) not null check(amount>0),
 currency text not null references public.currencies(code), account_id uuid references public.financial_accounts(id),
 created_by uuid references auth.users(id), created_at timestamptz not null default now()
);
create table if not exists public.stock_movements (
 id uuid primary key default gen_random_uuid(), product_id uuid not null references public.products(id),
 movement_type text not null check(movement_type in ('opening','purchase','sale','sales_return','purchase_return','adjustment')),
 quantity_delta numeric(18,3) not null, reference_table text, reference_id uuid,
 client_mutation_id uuid unique, notes text, created_by uuid references auth.users(id), created_at timestamptz not null default now()
);
create table if not exists public.money_movements (
 id uuid primary key default gen_random_uuid(), direction text not null check(direction in ('receipt','payment')),
 party_type text check(party_type in ('customer','supplier','other')), party_id uuid,
 account_id uuid references public.financial_accounts(id), amount numeric(20,4) not null check(amount>0),
 currency text not null references public.currencies(code), exchange_rate numeric(20,8) not null default 1 check(exchange_rate>0),
 reference_table text, reference_id uuid, client_mutation_id uuid unique,
 notes text, created_by uuid references auth.users(id), created_at timestamptz not null default now()
);
create table if not exists public.journal_entries (
 id uuid primary key default gen_random_uuid(), entry_no bigint generated by default as identity unique,
 entry_date date not null default current_date, description text not null,
 source_table text, source_id uuid, status text not null default 'draft' check(status in ('draft','posted','reversed')),
 created_by uuid references auth.users(id), created_at timestamptz not null default now(), posted_at timestamptz
);
create table if not exists public.journal_lines (
 id uuid primary key default gen_random_uuid(), entry_id uuid not null references public.journal_entries(id) on delete restrict,
 account_code text not null, account_name text not null, debit numeric(20,4) not null default 0 check(debit>=0),
 credit numeric(20,4) not null default 0 check(credit>=0), currency text not null references public.currencies(code),
 check ((debit=0) <> (credit=0))
);
create table if not exists public.sync_operations (
 client_mutation_id uuid primary key, device_id text not null, entity text not null,
 entity_id uuid not null, operation text not null, payload jsonb not null,
 base_version integer not null default 0, status text not null default 'received' check(status in ('received','applied','conflict','rejected')),
 server_version integer, conflict_detail jsonb, user_id uuid references auth.users(id),
 created_at timestamptz not null default now(), processed_at timestamptz
);
create table if not exists public.audit_log (
 id bigint generated always as identity primary key, table_name text not null, record_id uuid,
 action text not null, old_data jsonb, new_data jsonb, changed_by uuid references auth.users(id),
 changed_at timestamptz not null default now()
);

-- Restrict direct client access by default. Application writes should be routed through reviewed RPCs.
do $$ declare t text; begin
 foreach t in array array['app_profiles','currencies','exchange_rates','units','products','customers','suppliers','financial_accounts','sales_invoices','sales_invoice_lines','purchase_invoices','purchase_invoice_lines','expenses','other_income','stock_movements','money_movements','journal_entries','journal_lines','sync_operations','audit_log']
 loop
  execute format('alter table public.%I enable row level security',t);
 end loop;
end $$;

-- Basic authenticated read policies. Do not grant anon access.
do $$ declare t text; begin
 foreach t in array array['currencies','exchange_rates','units','products','customers','suppliers','financial_accounts','sales_invoices','sales_invoice_lines','purchase_invoices','purchase_invoice_lines','expenses','other_income','stock_movements','money_movements','journal_entries','journal_lines','sync_operations','audit_log']
 loop
  execute format('drop policy if exists %I on public.%I',t||'_authenticated_select',t);
  execute format('create policy %I on public.%I for select to authenticated using (true)',t||'_authenticated_select',t);
 end loop;
end $$;

-- Deliberately no client write policies in this starter schema. Add role-checked RPCs before production writes.
